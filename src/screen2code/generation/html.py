"""HTML/CSS adapter (GENERATION section 5): lowers the IR's layout intent to reusable CSS classes and semantic elements."""
from __future__ import annotations

import copy
from typing import Any, Callable

from .common import FONT_STACKS, JSON, Plan, Report, css_px, esc, num

ALIGN = {"start": "flex-start", "center": "center", "end": "flex-end", "stretch": "stretch", "baseline": "baseline"}
JUSTIFY = {"start": "flex-start", "center": "center", "end": "flex-end", "space-between": "space-between", "space-around": "space-around", "space-evenly": "space-evenly"}


class HtmlAdapter:
    id = "html"

    prop_mode = False  # React: inside a component definition, parameters are props
    dry = False  # dry runs compute declarations without touching the report (used for responsive diffs)

    def __init__(self) -> None:
        self.rules: list[tuple[str, list[tuple[str, str]]]] = []
        self.seen: set[str] = set()
        self.media: dict[str, list[tuple[str, list[tuple[str, str]]]]] = {}
        self.params: JSON | None = None
        self.inst: JSON | None = None

    # -- value lowering
    def color(self, ir: JSON, ref: JSON) -> str:
        if "literal" in ref:
            c = ref["literal"]
            return c["hex"].lower() if c["alpha"] == 1 else f"rgba({int(c['hex'][1:3], 16)},{int(c['hex'][3:5], 16)},{int(c['hex'][5:7], 16)},{num(c['alpha'])})"
        return f"var(--{self.tok_name(ir, ref['token'])})"

    def dim(self, ir: JSON, d: JSON) -> str:
        return css_px(d["px"]) if "px" in d else f"var(--{self.tok_name(ir, d['token'])})"

    def tok_name(self, ir: JSON, tid: str) -> str:
        for cat, d in ir["tokens"].items():
            if cat != "scales" and tid in d:
                return d[tid]["name"].replace("/", "-").replace(" ", "-").lower()
        return tid

    # -- rules
    def add(self, cls: str, decl: list[tuple[str, str]]) -> None:
        if decl and cls not in self.seen:  # a component's rules are emitted once, however many instances use them
            self.seen.add(cls)
            self.rules.append((cls, decl))

    def emit(self, ir: JSON, plan: Plan, read_asset: Callable[[str], bytes], report: Report) -> dict[str, bytes]:
        files: dict[str, bytes] = {}
        assets_out: dict[str, bytes] = {}
        self.ir, self.plan, self.report, self.read_asset, self.assets_out = ir, plan, report, read_asset, assets_out
        pages_html: dict[str, str] = {}
        for pid, fname in plan.pages.items():
            page = ir["pages"][pid]
            root = page["root"]
            body = self.node(root, None, 2)
            rootfill = (ir["nodes"][root].get("style") or {}).get("fill")
            bodybg = self.color(ir, rootfill["color"]) if rootfill and rootfill["kind"] == "solid" else "#ffffff"
            pages_html[fname] = (
                "<!doctype html>\n<html lang=\"en\">\n<head>\n  <meta charset=\"utf-8\">\n  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
                f"  <title>{esc(page['name'])}</title>\n  <link rel=\"stylesheet\" href=\"styles.css\">\n</head>\n<body style=\"background:{bodybg}\">\n{body}</body>\n</html>\n"
            )
        for pid in plan.pages:
            self.emit_responsive(pid)
        for fname, h in pages_html.items():
            files[fname] = h.encode()
        files["styles.css"] = self.stylesheet().encode()
        for path, data in assets_out.items():
            files[path] = data
        return files

    def stylesheet(self) -> str:
        ir = self.ir
        out = ["/* Generated by Screen2Code. Edit freely; regenerate from the IR to refresh. */"]
        root_vars: list[str] = []
        dark_vars: list[str] = []
        modes = ir["modes"]
        default_mode = ir["project"].get("default_mode")
        for cat, d in ir["tokens"].items():
            if cat in ("scales", "type"):  # composite type styles are lowered to font declarations, not custom properties
                continue
            for t in d.values():
                name = self.tok_name(ir, t["id"])
                if "value" in t:
                    v = t["value"]
                    root_vars.append(f"--{name}: {v['hex'].lower() if isinstance(v, dict) and 'hex' in v else css_px(v['px']) if isinstance(v, dict) and 'px' in v else v};")
                else:
                    for m, bm in sorted(t["by_mode"].items()):
                        v = bm["value"]
                        txt = f"--{name}: {v['hex'].lower() if 'hex' in v else css_px(v['px'])};"
                        (root_vars if m == default_mode or len(modes) == 1 else dark_vars).append(txt)
        if root_vars:
            out.append(":root {\n  " + "\n  ".join(root_vars) + "\n}")
        if dark_vars:
            out.append("@media (prefers-color-scheme: dark) {\n  :root {\n    " + "\n    ".join(dark_vars) + "\n  }\n}")
        out.append("*, *::before, *::after { box-sizing: border-box; }\nbody { margin: 0; }\nh1, h2, h3, h4, h5, h6, p { margin: 0; }\nbutton { appearance: none; border: 0; font: inherit; margin: 0; color: inherit; background: none; text-align: inherit; }\nimg { display: block; }")
        for cls, decl in self.rules:
            out.append(f".{cls} {{\n" + "".join(f"  {k}: {v};\n" for k, v in decl) + "}")
        for query in sorted(self.media):
            body = "\n".join(f"  {sel} {{\n" + "".join(f"    {k}: {v};\n" for k, v in decl) + "  }" for sel, decl in self.media[query])
            out.append(f"@media {query} {{\n{body}\n}}")
        return "\n\n".join(out) + "\n"

    # -- nodes
    RESET = {"padding": "0", "margin": "0", "gap": "0", "flex": "0 1 auto", "align-self": "auto", "width": "auto", "height": "auto", "grid-template-columns": "none",
             "justify-content": "flex-start", "align-items": "stretch", "flex-direction": "row", "background-color": "transparent", "border": "0", "border-radius": "0", "min-width": "auto", "min-height": "auto"}

    def css_decls(self, n: JSON, parent: JSON | None) -> list[tuple[str, str]]:
        decl: list[tuple[str, str]] = []
        self.dry = True
        try:
            self.sizing(n, parent, decl)
            self.place(n, parent, decl)
            if n["kind"] == "text":
                st = n["text"]["style"]
                if "token" in st:
                    st = {**self.ir["tokens"]["type"][st["token"]]["value"], **st.get("overrides", {})}
                decl += [("font-size", self.dim(self.ir, st["size"])), ("font-weight", str(st["weight"]))]
                lh = st.get("line_height")
                if lh:
                    decl.append(("line-height", css_px(lh["px"]) if "px" in lh else num(lh["ratio"])))
            elif n["kind"] == "box":
                self.layout(n, decl)
                self.style(n, decl)
        finally:
            self.dry = False
        return decl

    def _threshold(self, page: JSON, b: Any) -> float | None:
        if isinstance(b, str):
            return float(page["breakpoints"][b]["selected"])
        return None if b is None else float(b)

    def emit_responsive(self, pid: str) -> None:
        """Lower the page's responsive patches to media queries (min/max width at the selected thresholds; never described as observed)."""
        ir = self.ir
        page = ir["pages"][pid]
        parents = {c: p for p, nn in ir["nodes"].items() for c in nn.get("children", [])}
        cls_by_id = {c["id"]: c for c in page["viewport_classes"]}
        for rs in page["responsive"]:
            n = ir["nodes"][rs["target"]]
            parent = ir["nodes"].get(parents.get(rs["target"], ""))
            patched = copy.deepcopy(n)
            hide = False
            for op in rs["patch"]:
                if op["op"] == "hide":
                    hide = True
                elif op["op"] == "set":
                    cur = patched
                    keys = op["path"].split(".")
                    for k in keys[:-1]:
                        cur = cur.setdefault(k, {})
                    cur[keys[-1]] = copy.deepcopy(op["value"])
                else:
                    self.report.deviate(rs["target"], f"responsive operation {op['op']!r} is not lowered by this adapter")
            if hide:
                changes = [("display", "none")]
            else:
                base = dict(self.css_decls(n, parent))
                new = dict(self.css_decls(patched, parent))
                changes = [(k, v) for k, v in new.items() if base.get(k) != v] + [(k, self.RESET.get(k, "initial")) for k in base if k not in new]
            if not changes:
                continue
            for vc in rs["when"]:
                c = cls_by_id[vc]
                lo, hi = self._threshold(page, c["min"]), self._threshold(page, c["max_exclusive"])
                parts = ([f"(min-width: {num(lo)}px)"] if lo else []) + ([f"(max-width: {num(hi - 0.02)}px)"] if hi is not None else [])
                self.media.setdefault(" and ".join(parts), []).append((f".{self.plan.names[rs['target']]}", changes))

    def instance(self, n: JSON, parent: JSON | None, depth: int) -> str:
        cmp = self.ir["components"][n["instance"]["component"]]
        outer, outer_inst = self.params, self.inst
        self.params, self.inst = n["instance"]["params"], n
        icls = self.plan.names[n["id"]]
        decl: list[tuple[str, str]] = []
        self.sizing(n, parent, decl)
        self.place(n, parent, decl)
        self.add(icls, decl)
        for ov in n["instance"].get("overrides", []):
            if ov["path"] == "text.style.line_height":
                lh = ov["value"]
                self.rules.append((f"{icls} .{self.plan.names[ov['target']]}", [("line-height", css_px(lh["px"]) if "px" in lh else num(lh["ratio"]))]))
            else:
                self.report.deviate(n["id"], f"instance override {ov['path']!r} is not applied by the HTML adapter")
        try:
            return self.node(cmp["root"], parent, depth)
        finally:
            self.params, self.inst = outer, outer_inst

    def node(self, nid: str, parent: JSON | None, depth: int) -> str:
        ir, n = self.ir, self.ir["nodes"][nid]
        if n["kind"] == "instance":
            return self.instance(n, parent, depth)
        cls = rule = self.plan.names[nid]  # `rule` owns the CSS; `cls` is the class attribute (component class + instance class for a root)
        in_instance = self.inst is not None
        is_root = in_instance and nid == ir["components"][self.inst["instance"]["component"]]["root"]
        if is_root:
            cls = f"{cls} {self.plan.names[self.inst['id']]}"
        ident = self.inst["id"] if is_root else nid
        attr = f' data-s2c-id="{ident}"' if self.plan.options["instrumentation"] and (is_root or not in_instance) else ""
        ind = "  " * depth
        decl: list[tuple[str, str]] = []
        self.sizing(n, parent, decl)
        self.place(n, parent, decl)
        kind, role = n["kind"], n.get("role")
        if kind == "text":
            return self.text(n, cls, attr, decl, ind)
        if kind in ("image", "opaque"):
            return self.picture(n, cls, attr, decl, ind)
        if kind == "shape":
            self.style(n, decl)
            self.add(rule, decl)
            return f'{ind}<div class="{cls}"{attr}></div>\n'
        # box
        self.layout(n, decl)
        self.style(n, decl)
        self.add(rule, decl)
        kids = "".join(self.node(c, n, depth + 1) for c in n.get("children", []))
        tag, extra = "div", ""
        if role == "button":
            tag, extra = "button", ' type="button"'
        elif role == "separator":
            extra = ' role="separator"'
        elif role == "nav":
            tag = "nav"
        if kids:
            return f"{ind}<{tag} class=\"{cls}\"{extra}{attr}>\n{kids}{ind}</{tag}>\n"
        return f"{ind}<{tag} class=\"{cls}\"{extra}{attr}></{tag}>\n"

    def layout(self, n: JSON, decl: list[tuple[str, str]]) -> None:
        lay = n.get("layout")
        if not lay or lay["mode"] == "none":
            return
        m = lay["mode"]
        if m in ("stack", "flex"):
            s = lay["stack" if m == "stack" else "flex"]
            decl += [("display", "flex"), ("flex-direction", "row" if s["axis"] == "horizontal" else "column")]
            if m == "flex" and s.get("wrap"):
                decl.append(("flex-wrap", "wrap"))
            if "gap" in s:
                decl.append(("gap", self.dim(self.ir, s["gap"])))
            decl.append(("align-items", ALIGN[s.get("align", "stretch")]))
            decl.append(("justify-content", JUSTIFY[s.get("distribute", "start")]))
        elif m == "grid":
            g = lay["grid"]
            cols = []
            for t in g["columns"]:
                cols.append(f"minmax(0, {num(t.get('weight', 1))}fr)" if t["kind"] == "share" else css_px(t["px"]) if t["kind"] == "fixed" else "auto")
            decl += [("display", "grid"), ("grid-template-columns", " ".join(cols))]
            if "gap" in g:
                decl.append(("gap", f"{self.dim(self.ir, g['gap'].get('row', {'px': 0}))} {self.dim(self.ir, g['gap'].get('col', {'px': 0}))}"))
        elif m == "absolute":
            decl.append(("position", "relative"))
            self.dry or self.report.fallbacks.append({"node": n["id"], "mode": "absolute", "reason": lay["absolute"]["fallback"]["reason"]})
        elif m == "overlay":
            decl.append(("position", "relative"))
            self.dry or self.report.deviate(n["id"], "overlay lowered with absolute positioning; anchors are approximated")

    def sizing(self, n: JSON, parent: JSON | None, decl: list[tuple[str, str]]) -> None:
        sz = n.get("size") or {}
        pl = (parent or {}).get("layout") or {}
        pmode = pl.get("mode")
        axis = (pl.get("stack") or pl.get("flex") or {}).get("axis")
        for a, prop in (("w", "width"), ("h", "height")):
            s = sz.get(a)
            if not s:
                continue
            main = (axis == "horizontal" and a == "w") or (axis == "vertical" and a == "h")
            if s["kind"] == "fixed":
                decl.append((prop, css_px(s["px"])))
                if pmode in ("stack", "flex") and main:
                    decl.append(("flex-shrink", "0"))
            elif s["kind"] == "fill":
                if pmode in ("stack", "flex"):
                    decl += [("flex", "1 1 0"), ("min-width" if a == "w" else "min-height", "0")] if main else [("align-self", "stretch")]
                elif pmode is None:
                    decl.append((prop, "100%"))
        if "aspect" in sz and sz["aspect"]:
            decl.append(("aspect-ratio", num(sz["aspect"])))
        sp = n.get("spacing") or {}
        for key in ("padding", "margin"):
            ins = sp.get(key)
            if ins:
                v = [self.dim(self.ir, ins.get(side, ins.get("all", {"px": 0}))) for side in ("top", "right", "bottom", "left")]
                decl.append((key, " ".join(v)))

    def place(self, n: JSON, parent: JSON | None, decl: list[tuple[str, str]]) -> None:
        pl = n.get("placement") or {}
        if "absolute" in pl:
            a = pl["absolute"]
            decl.append(("position", "absolute"))
            for side in ("left", "top", "right", "bottom"):
                if side in a:
                    decl.append((side, self.dim(self.ir, a[side])))
        if "grid" in pl:
            g = pl["grid"]
            decl += [("grid-column", f"{g['col'][0]} / span {g['col'][1]}"), ("grid-row", f"{g['row'][0]} / span {g['row'][1]}")]

    def style(self, n: JSON, decl: list[tuple[str, str]]) -> None:
        st = n.get("style") or {}
        f = st.get("fill")
        if f and f["kind"] == "solid":
            decl.append(("background-color", self.color(self.ir, f["color"])))
        elif f and f["kind"] == "gradient":
            stops = ", ".join(f"{self.color(self.ir, s['color'])} {num(s['pos'] * 100)}%" for s in f["stops"])
            decl.append(("background-image", f"{'linear' if f['type'] == 'linear' else 'radial'}-gradient({(num(f.get('angle', 180)) + 'deg, ') if f['type'] == 'linear' else ''}{stops})"))
        b = st.get("border")
        if b and "all" in b["sides"]:
            s = b["sides"]["all"]
            decl.append(("border", f"{self.dim(self.ir, s['width'])} {s['style']} {self.color(self.ir, s['color'])}"))
        r = st.get("radius")
        if r:
            decl.append(("border-radius", "9999px" if r.get("pill") else self.dim(self.ir, r["all"]) if "all" in r else " ".join(self.dim(self.ir, r.get(k, {"px": 0})) for k in ("tl", "tr", "br", "bl"))))
        if "opacity" in st:
            decl.append(("opacity", num(st["opacity"])))
        if st.get("clip") == "clipped":
            decl.append(("overflow", "hidden"))
        for s in st.get("shadows", []):
            decl.append(("box-shadow", f"{'inset ' if s.get('inset') else ''}{self.dim(self.ir, s['x'])} {self.dim(self.ir, s['y'])} {self.dim(self.ir, s['blur'])} {self.color(self.ir, s['color'])}"))

    def text(self, n: JSON, cls: str, attr: str, decl: list[tuple[str, str]], ind: str) -> str:
        parts = self.text_parts(n, decl, cls)
        if parts is None:
            return ""
        tag, value = parts
        body = "<br>".join(esc(line) for line in (value or "").split("\n"))
        return f'{ind}<{tag} class="{cls}"{attr}>{body}</{tag}>\n'

    def text_parts(self, n: JSON, decl: list[tuple[str, str]], cls: str) -> tuple[str, str] | None:
        """Shared by the HTML and React adapters: builds the CSS and resolves tag and text value (None if the node cannot be emitted)."""
        t = n["text"]
        content = t["content"]
        if "param" in content:
            if self.prop_mode:
                content = {"value": "", "status": "inferred"}  # value supplied through props by the React adapter
            elif self.params is None or content["param"] not in self.params:
                self.report.deviate(n["id"], "parameter-bound text outside a component instance cannot be emitted")
                return None
            else:
                content = self.params[content["param"]]
        st = t["style"]
        if "token" in st:
            tok = self.ir["tokens"]["type"][st["token"]]["value"]
            st = {**tok, **st.get("overrides", {})}
        decl += [("font-family", FONT_STACKS[st["family"]["generic"]]), ("font-size", self.dim(self.ir, st["size"])), ("font-weight", str(st["weight"]))]
        if st.get("italic"):
            decl.append(("font-style", "italic"))
        lh = st.get("line_height")
        if lh:
            decl.append(("line-height", css_px(lh["px"]) if "px" in lh else num(lh["ratio"])))
        if "color" in st:
            decl.append(("color", self.color(self.ir, st["color"])))
        multiline = (t.get("truncation") or {}).get("mode") == "wrap"
        if not multiline:
            decl.append(("white-space", "nowrap"))
        self.add(cls, decl)
        status, value = content["status"], content["value"]
        if status == "unreadable":
            value = self.plan.options["placeholder_text"]
            self.report.deviate(n["id"], "unreadable text replaced by the configured placeholder string")
        elif status == "redacted":
            value = (content.get("replacement") or {}).get("label", "")
            value = f"[{value}]" if value else ""
        elif status in ("uncertain",):
            self.report.uncertain_text.append({"node": n["id"], "value": value, "status": status})
        role = n.get("role")
        tag = f"h{t.get('heading_level', 2)}" if role == "heading" else "p"
        return tag, value

    def picture(self, n: JSON, cls: str, attr: str, decl: list[tuple[str, str]], ind: str) -> str:
        parts = self.picture_parts((n.get("media") or n["opaque"])["asset"], n["id"], decl, cls)
        if parts is None:
            return ""
        kind, path, iw = parts
        if kind == "placeholder":
            return f'{ind}<div class="{cls}"{attr} data-s2c-placeholder></div>\n'
        return f'{ind}<img class="{cls}"{attr} src="{path}" alt="" width="{iw.get("w", "")}" height="{iw.get("h", "")}">\n'

    asset_file_prefix, asset_url_prefix = "assets/", "assets/"

    def picture_parts(self, aid: Any, nid: str, decl: list[tuple[str, str]], cls: str) -> tuple[str, str | None, JSON] | None:
        """Shared policy + CSS for images: returns ('placeholder', None, {}) or ('img', url, intrinsic), applying the asset-rights policy."""
        if isinstance(aid, dict):
            aid = (self.params or {}).get(aid["param"], {}).get("asset")
            if aid is None:
                self.report.deviate(nid, "asset parameter has no value in this instance")
                return None
        a = self.ir["assets"][aid]
        policy = self.plan.options["asset_policy"]
        prov, rights = a["provenance"], a["rights_status"]
        applied = "n/a (placeholder)"
        use_placeholder = prov == "placeholder"
        if not use_placeholder:
            if rights == "unknown" and policy == "strict":
                use_placeholder, applied = True, "strict: excluded, replaced by a placeholder"
                self.report.warnings.append(f"asset {aid} excluded by strict asset policy (rights unknown)")
            else:
                applied = "default: included with warning" if rights == "unknown" and policy == "default" else "permissive: included" if rights == "unknown" else "included"
                if rights == "unknown" and policy == "default":
                    self.report.warnings.append(f"asset {aid} is a pixel crop of the reference with unknown rights; review before publishing")
        rec: JSON = {"id": aid, "provenance": prov, "rights_status": rights, "policy_applied": applied}
        if a.get("origin"):
            rec.update(origin_region=a["origin"].get("region"), lossy=a["origin"].get("lossy"), resolution_scale=a["origin"].get("resolution_scale"))
        self.report.assets.append(rec)
        if use_placeholder:
            self.report.placeholders.append({"asset": aid, "reason": (a.get("placeholder") or {}).get("reason", "excluded by policy")})
            h = a["hint"]
            decl += [("background-color", h["dominant_color"]["hex"].lower()), ("aspect-ratio", num(h["aspect"]))]
            self.add(cls, decl)
            return "placeholder", None, {}
        sha = a["content"]["ref"].split(":")[-1]
        self.assets_out[f"{self.asset_file_prefix}{sha}.png"] = self.read_asset(sha)
        decl += [("display", "block"), ("object-fit", "cover")]
        self.add(cls, decl)
        return "img", f"{self.asset_url_prefix}{sha}.png", a["content"].get("intrinsic", {})

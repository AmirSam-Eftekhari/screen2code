"""React (TypeScript) adapter (GENERATION section 2): the HTML adapter's CSS lowering with JSX output and typed components.

Generate-only: Screen2Code never builds or runs this project (SECURITY section 5). Dependencies are exact-pinned in package.json; a lockfile
must be created by the user with ``npm install --package-lock-only`` (not possible offline, so none is shipped).
"""
from __future__ import annotations

import json
import re
from typing import Any, Callable

from ..core.workspace import sanitize_name
from .common import JSON, Plan, Report, css_px, num
from .html import HtmlAdapter

PINNED = {"react": "18.3.1", "react-dom": "18.3.1", "@types/react": "18.3.12", "@types/react-dom": "18.3.1", "@vitejs/plugin-react": "4.3.4", "typescript": "5.6.3", "vite": "5.4.11"}


def pascal(s: str, fallback: str = "Component") -> str:
    parts = re.findall(r"[A-Za-z0-9]+", s)
    name = "".join(p[:1].upper() + p[1:] for p in parts) or fallback
    return name if not name[0].isdigit() else fallback + name


def jstr(s: str) -> str:
    return json.dumps(s, ensure_ascii=False).replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


class ReactAdapter(HtmlAdapter):
    id = "react"
    asset_file_prefix, asset_url_prefix = "public/assets/", "/assets/"

    def emit(self, ir: JSON, plan: Plan, read_asset: Callable[[str], bytes], report: Report) -> dict[str, bytes]:
        self.ir, self.plan, self.report, self.read_asset, self.assets_out = ir, plan, report, read_asset, {}
        self.cur_root = ""
        names: dict[str, str] = {}
        used: set[str] = set()
        for cid, c in sorted(ir["components"].items()):
            base = pascal(c["name"])
            n, k = base, 2
            while n in used:
                n, k = f"{base}{k}", k + 1
            used.add(n)
            names[cid] = n
        self.cnames = names
        files: dict[str, bytes] = {}
        for cid, cmp in sorted(ir["components"].items()):
            files[f"src/components/{names[cid]}.tsx"] = self.component_file(cid).encode()
        pages: dict[str, str] = {}
        for pid, fname in plan.pages.items():
            pname = pascal(ir["pages"][pid]["name"], "Page")
            pages[pid] = pname
            files[f"src/pages/{pname}.tsx"] = self.page_file(pid, pname).encode()
        first = sorted(plan.pages, key=lambda p: ir["pages"][p]["name"])[0]
        files["src/App.tsx"] = (f'import {{ {pages[first]} }} from "./pages/{pages[first]}";\n\nexport default function App() {{\n  return <{pages[first]} />;\n}}\n').encode()
        files["src/main.tsx"] = ('import React from "react";\nimport { createRoot } from "react-dom/client";\nimport App from "./App";\nimport "./styles.css";\n\n'
                                 'createRoot(document.getElementById("root")!).render(<React.StrictMode><App /></React.StrictMode>);\n').encode()
        for pid in plan.pages:
            self.emit_responsive(pid)
        files["src/styles.css"] = self.stylesheet().encode()
        files["index.html"] = ('<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="utf-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1" />\n'
                               f'    <title>{ir["project"]["name"].replace("<", "").replace(">", "")}</title>\n  </head>\n  <body>\n    <div id="root"></div>\n    <script type="module" src="/src/main.tsx"></script>\n  </body>\n</html>\n').encode()
        files["package.json"] = (json.dumps({"name": sanitize_name(ir["project"]["name"], "screen2code-app").lower(), "private": True, "version": "0.0.0", "type": "module",
                                             "scripts": {"dev": "vite", "build": "tsc --noEmit && vite build"}, "dependencies": {k: PINNED[k] for k in ("react", "react-dom")},
                                             "devDependencies": {k: v for k, v in PINNED.items() if k not in ("react", "react-dom")}}, indent=2) + "\n").encode()
        files["tsconfig.json"] = json.dumps({"compilerOptions": {"target": "ES2020", "lib": ["ES2020", "DOM"], "jsx": "react-jsx", "module": "ESNext", "moduleResolution": "bundler", "strict": True, "skipLibCheck": True, "noEmit": True}, "include": ["src"]}, indent=2).encode() + b"\n"
        files["vite.config.ts"] = b'import { defineConfig } from "vite";\nimport react from "@vitejs/plugin-react";\n\nexport default defineConfig({ plugins: [react()] });\n'
        files["README.md"] = ("# Generated by Screen2Code\n\nThis project was generated from a reconstructed UI IR. It has NOT been built or run by Screen2Code.\n\n"
                              "Review `s2c-report.json` / `REPORT.md` first (uncertain text, placeholders, asset provenance and rights).\n\n"
                              "```\nnpm install --package-lock-only   # create a lockfile with integrity hashes, then review it\nnpm install --ignore-scripts\nnpm run dev\n```\n").encode()
        files.update(self.assets_out)
        report.warnings.append("React output is generate-only: it has not been built or executed by Screen2Code, and no lockfile is included")
        return files

    # -- files
    def component_file(self, cid: str) -> str:
        cmp = self.ir["components"][cid]
        name = self.cnames[cid]
        props = [f"{p}: string" if s["type"] == "text" else f"{p}: string | null" for p, s in sorted(cmp["params"].items())]
        self.prop_mode, self.params, self.inst, self.cur_root = True, None, None, cmp["root"]
        body = self.jnode(cmp["root"], None, 2)
        self.prop_mode = False
        self.cur_root = ""
        return (f'import React from "react";\n\nexport type {name}Props = {{ {"; ".join(props + ["className?: string", "s2cId?: string"])} }};\n\n'
                f"export function {name}(props: {name}Props) {{\n  return (\n{body}  );\n}}\n")

    def page_file(self, pid: str, pname: str) -> str:
        self.prop_mode, self.params, self.inst = False, None, None
        used_before = set(self.cnames.values())
        body = self.jnode(self.ir["pages"][pid]["root"], None, 2)
        imports = "".join(f'import {{ {n} }} from "../components/{n}";\n' for n in sorted(used_before) if f"<{n} " in body)
        return f'import React from "react";\n{imports}\nexport function {pname}() {{\n  return (\n{body}  );\n}}\n'

    # -- JSX emission
    def jnode(self, nid: str, parent: JSON | None, depth: int) -> str:
        ir, n = self.ir, self.ir["nodes"][nid]
        ind = "  " * depth
        if n["kind"] == "instance":
            return self.jinstance(n, parent, ind)
        cls = rule = self.plan.names[nid]
        instr = self.plan.options["instrumentation"]
        root_in_comp = self.prop_mode and nid == self.cur_root
        attr = (" data-s2c-id={props.s2cId}" if root_in_comp else f' data-s2c-id="{nid}"') if instr and (root_in_comp or not self.prop_mode) else ""
        cls_attr = f' className={{"{cls}" + (props.className ? " " + props.className : "")}}' if root_in_comp else f' className="{cls}"'
        decl: list[tuple[str, str]] = []
        self.sizing(n, parent, decl)
        self.place(n, parent, decl)
        kind, role = n["kind"], n.get("role")
        if kind == "text":
            parts = self.text_parts(n, decl, cls)
            if parts is None:
                return ""
            tag, value = parts
            content = n["text"]["content"]
            if "param" in content and self.prop_mode:
                expr = f"{{props.{content['param']}}}"
            else:
                expr = "<br />".join("{" + jstr(line) + "}" for line in (value or "").split("\n"))
            return f"{ind}<{tag}{cls_attr}{attr}>{expr}</{tag}>\n"
        if kind in ("image", "opaque"):
            media = (n.get("media") or n["opaque"])["asset"]
            if isinstance(media, dict) and self.prop_mode:
                p = media["param"]
                self.add(rule, decl + [("display", "block"), ("object-fit", "cover")])
                return (f"{ind}{{props.{p} ? <img{cls_attr}{attr} src={{props.{p}}} alt=\"\" /> : <div{cls_attr}{attr} data-s2c-placeholder=\"\" />}}\n")
            parts = self.picture_parts(media, nid, decl, cls)
            if parts is None:
                return ""
            k, url, iw = parts
            if k == "placeholder":
                return f'{ind}<div{cls_attr}{attr} data-s2c-placeholder="" />\n'
            return f'{ind}<img{cls_attr}{attr} src="{url}" alt="" width={{{iw.get("w", 0)}}} height={{{iw.get("h", 0)}}} />\n'
        if kind == "shape":
            self.style(n, decl)
            self.add(rule, decl)
            return f"{ind}<div{cls_attr}{attr} />\n"
        self.layout(n, decl)
        self.style(n, decl)
        self.add(rule, decl)
        kids = "".join(self.jnode(c, n, depth + 1) for c in n.get("children", []))
        tag, extra = "div", ""
        if role == "button":
            tag, extra = "button", ' type="button"'
        elif role == "separator":
            extra = ' role="separator"'
        elif role == "nav":
            tag = "nav"
        return f"{ind}<{tag}{cls_attr}{extra}{attr}>\n{kids}{ind}</{tag}>\n" if kids else f"{ind}<{tag}{cls_attr}{extra}{attr} />\n"

    def jinstance(self, n: JSON, parent: JSON | None, ind: str) -> str:
        cid = n["instance"]["component"]
        cmp = self.ir["components"][cid]
        icls = self.plan.names[n["id"]]
        decl: list[tuple[str, str]] = []
        self.sizing(n, parent, decl)
        self.place(n, parent, decl)
        self.add(icls, decl)
        props: list[str] = []
        for pname, spec in sorted(cmp["params"].items()):
            val = n["instance"]["params"].get(pname)
            if spec["type"] == "text":
                v = val or {"value": "", "status": "unreadable"}
                text = v["value"] if v["status"] != "unreadable" else self.plan.options["placeholder_text"]
                if v["status"] == "uncertain":
                    self.report.uncertain_text.append({"node": n["id"], "value": v["value"], "status": "uncertain", "param": pname})
                if v["status"] == "unreadable":
                    self.report.deviate(n["id"], "unreadable text replaced by the configured placeholder string")
                props.append(f"{pname}={{{jstr(text or '')}}}")
            else:
                src = self.instance_asset(n, pname, val, cmp, icls)
                props.append(f"{pname}={{{jstr(src) if src else 'null'}}}")
        for ov in n["instance"].get("overrides", []):
            if ov["path"] == "text.style.line_height":
                lh = ov["value"]
                self.rules.append((f"{icls} .{self.plan.names[ov['target']]}", [("line-height", css_px(lh["px"]) if "px" in lh else num(lh["ratio"]))]))
            else:
                self.report.deviate(n["id"], f"instance override {ov['path']!r} is not applied by the React adapter")
        sid = f' s2cId="{n["id"]}"' if self.plan.options["instrumentation"] else ""
        return f'{ind}<{self.cnames[cid]} {" ".join(props)} className="{icls}"{sid} />\n'

    def instance_asset(self, n: JSON, pname: str, val: JSON | None, cmp: JSON, icls: str) -> str | None:
        aid = (val or {}).get("asset")
        if not aid:
            self.report.deviate(n["id"], f"asset parameter {pname!r} has no value")
            return None
        probe: list[tuple[str, str]] = []
        node_id = cmp["params"][pname]["bind"]["node"]
        parts = self.picture_parts(aid, n["id"], probe, "")
        if parts is None:
            return None
        if parts[0] == "placeholder":  # per-instance placeholder look through a descendant rule
            a = self.ir["assets"][aid]
            self.rules.append((f"{icls} .{self.plan.names[node_id]}", [("background-color", a["hint"]["dominant_color"]["hex"].lower()), ("aspect-ratio", num(a["hint"]["aspect"]))]))
            return None
        return parts[1]
